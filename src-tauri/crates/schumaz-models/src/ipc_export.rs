fn render_command_entry(ctx: &FrameworkExporter<'_>, func: &Function) -> Result<String, Error> {
    let mut arg_defs = Vec::with_capacity(func.args().len());
    let mut invoke_fields = Vec::with_capacity(func.args().len());
    for (raw_name, raw_ty) in func.args() {
        let camel = raw_name.to_lower_camel_case();
        let phased = select_phase_datatype(raw_ty, ctx.types, Phase::Deserialize);
        let ts_ty = ctx.reference(&phased)?;
        arg_defs.push(format!("{camel}: {ts_ty}"));
        invoke_fields.push(camel);
    }

    let ret_ts = match func.result() {
        None => "void".to_string(),
        Some(dt) => {
            let phased = select_phase_datatype(dt, ctx.types, Phase::Serialize);
            ctx.reference(&phased)?
        }
    };

    let invoke_call = if invoke_fields.is_empty() {
        format!(r#"__TAURI_INVOKE<{ret_ts}>("{}")"#, func.name())
    } else {
        format!(
            r#"__TAURI_INVOKE<{ret_ts}>("{}", {{ {} }})"#,
            func.name(),
            invoke_fields.join(", ")
        )
    };

    Ok(format!("({}) => {invoke_call}", arg_defs.join(", ")))
}

fn render_runtime(
    ctx: &mut FrameworkExporter<'_>,
    functions: &[Function],
    events: &[IpcEventSpec],
) -> Result<Cow<'static, str>, Error> {
    let mut cmds_struct = Struct::named();
    for func in functions {
        let js_name = func.name().to_lower_camel_case();
        let entry = render_command_entry(ctx, func)?;
        let mut field = Field::new(define(entry).into());
        field.docs = func.docs.clone();
        field.deprecated = func.deprecated.clone();
        cmds_struct = cmds_struct.field(js_name, field);
    }
    let commands_ts = format!(
        "/** Commands */\nexport const commands = {};",
        ctx.reference(&cmds_struct.build())?
    );

    let mut events_struct = Struct::named();
    let mut sorted_events: BTreeMap<&str, &IpcEventSpec> = BTreeMap::new();
    for ev in events {
        sorted_events.insert(ev.struct_name, ev);
    }
    for ev in sorted_events.into_values() {
        let camel = ev.struct_name.to_lower_camel_case();
        let ser_dt = select_phase_datatype(&ev.data_type, ctx.types, Phase::Serialize);
        let de_dt = select_phase_datatype(&ev.data_type, ctx.types, Phase::Deserialize);
        let ser_ts = ctx.reference(&ser_dt)?;
        let de_ts = ctx.reference(&de_dt)?;
        let name_lit = serde_json::to_string(&ev.event_name)
            .map_err(|e| Error::framework("Failed to serialize event name", e))?;
        let val = format!("makeEvent<{ser_ts}, {de_ts}>({name_lit})");
        events_struct = events_struct.field(camel, Field::new(define(val).into()));
    }
    let events_ts = format!(
        "/** Events */\nexport const events = {};",
        ctx.reference(&events_struct.build())?
    );

    let user_types_raw = ctx.render_types()?;
    let user_types = user_types_raw.trim();

    Ok(Cow::Owned(format!(
        "{TAURI_API_IMPORT}\n\n{commands_ts}\n\n{events_ts}\n\n/* Types */\n{user_types}\n\n/* Tauri Specta runtime */\n{MAKE_EVENT_IMPL_TS}"
    )))
}

fn build_exporter(functions: Vec<Function>, events: Vec<IpcEventSpec>) -> Exporter {
    Exporter::from(Typescript::default())
        .framework_prelude(FRAMEWORK_PRELUDE)
        .framework_runtime(move |mut ctx| render_runtime(&mut ctx, &functions, &events))
}

/// Renders the full TypeScript IPC bindings file as an in-memory string.
pub fn export_ts_string() -> Result<String, Error> {
    let (types, functions, events) = collect_ipc_surface();
    let exporter = build_exporter(functions, events);
    exporter.export(&types, BigIntToNumberPhasesFormat::new())
}

/// Exports the TypeScript IPC bindings file to a target path without linking Tauri or WebView2.
pub fn export_bindings_to(path: impl AsRef<Path>) -> Result<(), Error> {
    let (types, functions, events) = collect_ipc_surface();
    let exporter = build_exporter(functions, events);
    exporter.export_to(path, &types, BigIntToNumberPhasesFormat::new())
}

/// Regenerates `src/types/bindings.ts` in the repository root.
pub fn export_bindings() {
    let out_path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/types/bindings.ts");
    export_bindings_to(out_path).expect("Failed to export typescript bindings");
}
