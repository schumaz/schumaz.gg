/// Marker return type used by `schumaz-models` stub signatures so Tauri command
/// `Result<T, E>` wrappers mirror `tauri-specta` TypeScript return types (`T` or `null`)
/// without registering `std::result::Result` into exported user types.
pub struct CmdResult<T>(PhantomData<T>);

impl<T: Type> Type for CmdResult<T> {
    fn definition(types: &mut Types) -> DataType {
        types.define::<T>()
    }
}

